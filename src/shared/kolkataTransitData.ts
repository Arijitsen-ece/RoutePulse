export function generateDailyTripsForRoutes(routes: TransitRoute[]): ScheduledTrip[] {
  const trips: ScheduledTrip[] = [];
  for (const route of routes) {
    // Do not generate fabricated official departures for routes without schedule data
    if (route.timetableBasis === 'UNAVAILABLE') continue;

    const isEstimated =
      route.timetableBasis === 'ESTIMATED_FREQUENCY' ||
      route.timetableBasis === 'SYNTHETIC_DEMO' ||
      route.timetableBasis === 'PASSENGER_OBSERVATION';

    const [startH, startM] = route.firstDeparture.split(':').map(Number);
    const [endH, endM] = route.lastDeparture.split(':').map(Number);
    if (!Number.isFinite(startH) || !Number.isFinite(startM) || !Number.isFinite(endH) || !Number.isFinite(endM)) {
      continue;
    }
    const startTotal = startH * 60 + startM;
    const endTotal = endH * 60 + endM;
    const durationMin = route.stopSequence[route.stopSequence.length - 1]?.scheduledOffsetMin ?? 55;
    const stepMin = Math.max(10, route.frequencyMin * 2);
    let index = 1;
    for (let t = startTotal; t <= endTotal; t += stepMin) {
      const depH = String(Math.floor(t / 60)).padStart(2, '0');
      const depM = String(t % 60).padStart(2, '0');
      const arrTotal = t + durationMin;
      const arrH = String(Math.floor(arrTotal / 60) % 24).padStart(2, '0');
      const arrM = String(arrTotal % 60).padStart(2, '0');
      trips.push({
        tripId: `trip_${route.routeId}_out_${index}`,
        routeId: route.routeId,
        direction: 'OUTBOUND',
        headsign: route.destination,
        departureTime: `${depH}:${depM}`,
        arrivalTime: `${arrH}:${arrM}`,
        operatingDays: route.operatingDays,
        isEstimated,
        timetableBasis: route.timetableBasis,
      });
      index++;
    }
  }
  return trips;
}

