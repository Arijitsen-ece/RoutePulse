const savedLang =
  typeof window !== 'undefined' ? (localStorage.getItem(LANG_STORAGE_KEY) as SupportedLanguage | null) : null;

i18n.use(initReactI18next).init({
  resources,
  lng: savedLang && ['en', 'hi', 'bn'].includes(savedLang) ? savedLang : 'en',
  fallbackLng: 'en',
  interpolation: {
    escapeValue: false,
  },
});

export function setAppLanguage(lang: SupportedLanguage) {
  i18n.changeLanguage(lang);
  if (typeof window !== 'undefined') {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
    document.documentElement.lang = lang;
  }
}

export function hasChosenInitialLanguage(): boolean {
  if (typeof window === 'undefined') return true;
  return Boolean(localStorage.getItem(LANG_STORAGE_KEY));
}

export default i18n;
